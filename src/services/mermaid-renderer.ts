/** 把依赖图渲染成 Mermaid 文本（只做渲染，不做分析）。 */
import type { DependencyReport } from './dependency-analyzer.js'

export interface MermaidOptions {
  maxEdges?: number
}

export interface MermaidResult {
  mermaid: string
  omittedEdges: number
}

function sanitizeLabel(value: string): string {
  return value.replace(/"/g, "'")
}

export function renderDependencyGraph(report: DependencyReport, options: MermaidOptions = {}): MermaidResult {
  const maxEdges = options.maxEdges ?? 250
  const cycled = new Set<string>()
  for (const cycle of report.cycles) for (const moduleName of cycle.modules) cycled.add(moduleName)

  const used = new Set<string>()
  for (const edge of report.edges) {
    used.add(edge.from)
    used.add(edge.to)
  }
  for (const moduleName of cycled) used.add(moduleName)

  const ordered = [...used].sort((left, right) => left.localeCompare(right))
  const ids = new Map<string, string>()
  ordered.forEach((moduleName, index) => ids.set(moduleName, 'm' + index))

  const lines: string[] = []
  lines.push('graph TD')
  lines.push('  %% ' + (report.language === 'python' ? 'Python' : 'TypeScript/JavaScript') + ' import graph generated by dsh-projectops (static, heuristic)')

  const shownEdges = report.edges.slice(0, maxEdges)
  for (const edge of shownEdges) {
    const from = ids.get(edge.from)
    const to = ids.get(edge.to)
    if (from === undefined || to === undefined) continue
    const arrow = edge.scope === 'nested' ? ' -.-> ' : ' --> '
    lines.push('  ' + from + '["' + sanitizeLabel(edge.from) + '"]' + arrow + to + '["' + sanitizeLabel(edge.to) + '"]')
  }

  if (report.cycles.length > 0) {
    lines.push('  classDef cycle fill:#ffe2e2,stroke:#d64545,stroke-width:2px;')
    const cycleIds = report.cycles
      .flatMap((cycle) => cycle.modules)
      .map((moduleName) => ids.get(moduleName))
      .filter((id): id is string => id !== undefined)
    if (cycleIds.length > 0) lines.push('  class ' + [...new Set(cycleIds)].join(',') + ' cycle')
  }

  if (report.edges.length > shownEdges.length) {
    lines.push('  %% 省略 ' + (report.edges.length - shownEdges.length) + ' 条边（超过渲染上限 ' + maxEdges + '）')
  }

  return { mermaid: lines.join('\n'), omittedEdges: report.edges.length - shownEdges.length }
}
